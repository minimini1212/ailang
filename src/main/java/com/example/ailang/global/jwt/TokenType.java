package com.example.ailang.global.jwt;

/**
 * 토큰이 «무엇을 위한 것인가».
 *
 * 🔴 이게 없어서 액세스 토큰과 리프레시 토큰이 구분되지 않았다.
 *    둘은 만료 시간만 다르고 subject·서명키·클레임이 전부 같았고, 인증 필터는
 *    서명과 만료만 봤다. 그래서 아래 셋이 동시에 성립했다.
 *
 *    ① 리프레시 토큰을 accessToken 쿠키 자리에 넣으면 모든 API 가 통과했다.
 *       즉 리프레시 토큰은 «유효기간 7일짜리 전체 API 자격증명» 이었다.
 *    ② 로그아웃은 액세스 토큰만 블랙리스트에 넣는다. 유출된 리프레시 토큰은
 *       로그아웃 이후에도 만료까지 계속 살아 있었다.
 *    ③ 서버가 FastAPI 를 부를 때 쓰는 토큰도 학생 토큰과 똑같이 생겼다.
 *
 * 🎯 종류를 claim 으로 박아 두고 «쓰이는 자리마다 요구» 하면 셋이 함께 닫힌다.
 */
public enum TokenType {

    /** 매 요청의 신분증. 짧게 산다. */
    ACCESS,

    /** 액세스 토큰을 다시 받기 위한 것. 오직 재발급에서만 쓴다. */
    REFRESH,

    /** 서버가 서버를 부를 때. 학생이 아니다 — 사람 계정으로 취급하지 않는다. */
    SERVICE;

    /** JWT 안에 들어가는 claim 이름. */
    public static final String CLAIM = "typ";
}
