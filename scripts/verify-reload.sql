PROMPT === ③ 챕터별 — 순번·제목·설명·문제수·난이도 ===
SELECT c.ORDER_NUM, c.TITLE, c.DESCRIPTION,
       COUNT(p.ID) 문제,
       SUM(CASE WHEN p.DIFFICULTY='LOW' THEN 1 ELSE 0 END) 하,
       SUM(CASE WHEN p.DIFFICULTY='MEDIUM' THEN 1 ELSE 0 END) 중,
       SUM(CASE WHEN p.DIFFICULTY='HIGH' THEN 1 ELSE 0 END) 상,
       COUNT(DISTINCT p.TOPIC) 유형
  FROM CHAPTERS c LEFT JOIN PROBLEMS p ON p.CHAPTER_ID = c.ID
 GROUP BY c.ORDER_NUM, c.TITLE, c.DESCRIPTION
 ORDER BY c.ORDER_NUM;

