COL WHAT FORMAT A26
COL TITLE FORMAT A20
COL DESCRIPTION FORMAT A20

PROMPT === ① 건수 ===
SELECT 'CHAPTERS' WHAT, COUNT(*) N FROM CHAPTERS
UNION ALL SELECT 'PROBLEMS(REAL)', COUNT(*) FROM PROBLEMS WHERE SOURCE_TYPE='REAL'
UNION ALL SELECT 'TOPIC 채워진 문제', COUNT(*) FROM PROBLEMS WHERE TOPIC IS NOT NULL
UNION ALL SELECT 'TOPIC 고유값(유형)', COUNT(DISTINCT TOPIC) FROM PROBLEMS
UNION ALL SELECT 'SOURCE_ID 채워진 문제', COUNT(*) FROM PROBLEMS WHERE SOURCE_ID IS NOT NULL
UNION ALL SELECT 'SOURCE_ID 고유값', COUNT(DISTINCT SOURCE_ID) FROM PROBLEMS;

